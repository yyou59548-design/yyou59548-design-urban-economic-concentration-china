#!/usr/bin/env python3
"""Read-only audit of the three author-retained, unredistributed TGIS volumes.

This checks ZIP file identity/CRC, path safety, uniqueness, all 5,401 checksums
in the extracted research release, and the 59 declared protected/companion
inputs. It does not execute or certify the 2,062 full GIS fields. No source
material is copied into this GitHub repository.

Examples:
 python scripts/audit_full_archive.py --part /path/Part1.zip --part /path/Part2.zip --part /path/Part3.zip --root /path/unpacked/Replication --output /tmp/audit.json
 python scripts/audit_full_archive.py --root /path/unpacked/Replication
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import json
import re
import stat
import subprocess
import sys
import zipfile
from pathlib import Path, PurePosixPath

EXPECTED_PARTS = {
    "TGIS_FINAL_02_Replication_Part1.zip": "fd98c3778651cdea9cd7628eae473a8b58c993645d432e24616be6a614d5e0b7",
    "TGIS_FINAL_02_Replication_Part2.zip": "ce76b7e106e6e1a931dfccc7e608428111ccfedc672851025b57ffea9ecb3c5e",
    "TGIS_FINAL_02_Replication_Part3.zip": "023230af7a4f1681f9792443a5ab1b13eb2e09464763fab3227ebc9755da2955",
}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(4 << 20), b""):
            h.update(block)
    return h.hexdigest()


def inspect_parts(paths: list[Path]):
    assert len(paths) == 3 and {p.name for p in paths} == set(EXPECTED_PARTS), "Exactly the named three volumes are required"
    findings = []
    seen = set()
    for file in sorted(paths, key=lambda p: p.name):
        assert file.is_file(), f"Missing volume {file}"
        digest = sha256(file)
        assert digest == EXPECTED_PARTS[file.name], f"Volume identity changed: {file.name}"
        with zipfile.ZipFile(file) as z:
            assert z.testzip() is None, f"ZIP CRC failure: {file.name}"
            records = z.infolist()
            for item in records:
                key = item.filename
                name = PurePosixPath(key)
                assert (not name.is_absolute() and not key.startswith("/") and "\\" not in key
                        and ".." not in name.parts and name.parts[0] == "Replication"), f"Unsafe entry: {key}"
                assert key not in seen, f"Duplicate ZIP member across volumes: {key}"
                seen.add(key)
                mode = (item.external_attr >> 16)
                assert not stat.S_ISLNK(mode), f"Unreviewed ZIP symlink: {key}"
        findings.append({"name": file.name, "sha256": digest, "bytes": file.stat().st_size, "members": len(records)})
    assert len(seen) == 5403, f"Expected 5,403 distinct members, got {len(seen)}"
    return {"volumes": findings, "unique_member_paths": len(seen), "zip_crc": "PASS", "path_safety": "PASS"}


def inspect_extracted(root: Path):
    root = root.expanduser().resolve()
    if not (root / "SHA256SUMS.txt").exists() and (root / "Replication/SHA256SUMS.txt").exists():
        root = root / "Replication"
    assert root.is_dir(), f"Missing extracted root: {root}"
    manifest = root / "SHA256SUMS.txt"
    assert manifest.is_file(), "Missing SHA256SUMS.txt"
    expected = {}
    for line in manifest.read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  (.+)", line)
        assert match is not None, "Malformed release manifest"
        digest, name = match.groups()
        path = PurePosixPath(name)
        assert not path.is_absolute() and ".." not in path.parts and name not in expected
        expected[name] = digest
    assert len(expected) == 5401, f"Expected 5,401 release digests, found {len(expected)}"
    # The two inventories themselves are present but not included in their own listing.
    actual = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}
    assert actual == set(expected) | {"SHA256SUMS.txt", "DELIVERY_MANIFEST.csv"}, f"Unexpected extracted-file inventory: {len(actual)}"
    failures = []
    for name, digest in expected.items():
        if sha256(root / name) != digest:
            failures.append(name)
    assert not failures, f"Release SHA256 failures: {failures[:10]}"
    # An independent manifest generated by the research archive itself covers the protected subset.
    checked = subprocess.run([sys.executable, "-B", str(root / "Replication_Inputs/verify_inputs.py")],
                             cwd=root, capture_output=True, text=True)
    assert checked.returncode == 0, checked.stderr or checked.stdout[-1000:]
    protected = json.loads(checked.stdout)
    assert protected["status"] == "PASS" and protected["failures"] == []
    assert protected["baseline_input_files"] == 10 and protected["required_companion_files"] == 3
    assert protected["supplemental_files"] == 46
    return {"research_files_verified": len(expected), "release_sha256": "PASS", "protected_inputs": protected,
            "scope": "Archive integrity, not a fresh end-to-end computation of all paper figures."}


def main():
    if not __debug__:
        raise RuntimeError("Scientific and integrity assertions require normal Python execution; do not use -O.")
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--part", type=Path, action="append", help="Supply each of the exact three original volume paths")
    p.add_argument("--root", type=Path, help="Existing extracted Replication directory (or parent)")
    p.add_argument("--output", type=Path, help="Optional JSON receipt outside the repository")
    args = p.parse_args()
    if not args.part and not args.root:
        p.error("Provide --part three times, --root, or both")
    try:
        record = {"status": "PASS", "scope": "Read-only source/archive integrity only"}
        if args.part:
            record["parts"] = inspect_parts(args.part)
        if args.root:
            record["extracted"] = inspect_extracted(args.root)
        print(json.dumps(record, ensure_ascii=False, indent=2))
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    except Exception as e:
        print(f"FAIL: {type(e).__name__}: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
